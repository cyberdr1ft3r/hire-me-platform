import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require(process.argv[2]);
const [,, , out, locale] = process.argv;
const { WEB, EMAIL, PW } = process.env;
const b = await chromium.launch({ channel: 'chrome', headless: true });
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
await ctx.addInitScript((l) => { try { localStorage.setItem('hireme.locale', l); } catch {} }, locale);
const p = await ctx.newPage();
await p.goto(`${WEB}/`);
await p.fill('input[name=email]', EMAIL); await p.fill('input[name=password]', PW); await p.click('button[type=submit]');
await p.getByRole('button', { name: /^Notifications/ }).waitFor();
await p.evaluate(() => { history.pushState({ hiremeHistoryIndex: 1 }, '', '/missions'); dispatchEvent(new PopStateEvent('popstate', { state: history.state })); });
await p.locator('.mission-directory__open').nth(1).waitFor();
await p.locator('.mission-directory__open').nth(1).click();
await p.locator('.mission-preview h2').waitFor();
await p.mouse.move(700, 880);
await p.waitForTimeout(400);
await p.screenshot({ path: out });
await b.close();
